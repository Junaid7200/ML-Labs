import streamlit as st
from PyPDF2 import PdfReader
from langchain_text_splitters import RecursiveCharacterTextSplitter
from sentence_transformers import SentenceTransformer
import faiss
import numpy as np
from gpt4all import GPT4All


def chunk_pdf_langchain(document):
    if document is None:
        return []

    pdf = PdfReader(document)
    full_text = ""

    for page in pdf.pages:
        if page.extract_text():
            full_text += page.extract_text() + "\n"

    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=1000,
        chunk_overlap=200,
        separators=["\n\n", "\n", ". ", " ", ""],
        length_function=len,
    )

    return text_splitter.split_text(full_text)


def embed_and_store_chunks(chunks):
    model = SentenceTransformer("sentence-transformers/all-MiniLM-L6-v2")
    embeddings = model.encode(chunks, show_progress_bar=True)
    embeddings = np.array(embeddings).astype("float32")
    dimension = embeddings.shape[1]
    index = faiss.IndexFlatL2(dimension)
    index.add(embeddings)
    return embeddings, index, chunks


def embed_question(question):
    model = SentenceTransformer("sentence-transformers/all-MiniLM-L6-v2")
    question_embedding = model.encode([question], show_progress_bar=False)
    return np.array(question_embedding).astype("float32")


def retrieve_relevant_chunks(question_embedding, index, chunks, top_k=3):
    distances, indices = index.search(question_embedding, top_k)
    relevant_chunks = [chunks[i] for i in indices[0]]
    return relevant_chunks


