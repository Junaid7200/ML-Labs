def generate_answer(relevant_chunks, question):
    context = "\n\n".join(relevant_chunks)
    
    prompt = f"""You are an AI assistant that helps users find information from a document.
Use the following context to answer the question at the end. If you don't know the answer, just say you don't know. Do not make up an answer.

Context:
{context}

Question: {question}
Answer:"""

    try:
        llm = load_llm()
        answer = llm.generate(prompt, max_tokens=512, temp=0.1)
        return answer
    except Exception as e:
        return f"⚠️ Model Error: {str(e)}\n\nHere are the relevant sections:\n\n{context}"




st.title("Retrieval-Augmented Generation")

st.write("""
        This application demonstrates Retrieval-Augmented Generation (RAG) using Streamlit.""")

st.write("""
        Upload a PDF document, ask questions about its content, and receive answers generated by a language model augmented with information retrieved from the document.
        """)

document = st.file_uploader("Upload your PDF document", type=["pdf"])

if document is not None:
    st.success("Document uploaded successfully!")

    # Process the document
    with st.spinner("Processing document..."):
        chunks = chunk_pdf_langchain(document)
    st.write(f"Document split into {len(chunks)} chunks")

    # Embed and index
    with st.spinner("Embedding and indexing document..."):
        embeddings, index, chunks = embed_and_store_chunks(chunks)
    st.write("Document indexed!")

    question = st.text_input("Ask a question about the document:")

    if question:
        st.write("You asked:", question)
        
        with st.spinner("Generating answer..."):
            # Get question embedding
            question_embedding = embed_question(question)

            # Retrieve relevant chunks
            relevant_chunks = retrieve_relevant_chunks(question_embedding, index, chunks)

            # Generate answer
            answer = generate_answer(relevant_chunks, question)

        st.write("Answer:", answer)